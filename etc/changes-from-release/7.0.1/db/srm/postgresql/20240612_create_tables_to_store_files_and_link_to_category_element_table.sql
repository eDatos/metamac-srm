CREATE TABLE TB_RESOURCE_FILE (
  ID BIGINT NOT NULL,
  "version" int8 NOT NULL,
  FILE_DATA BYTEA NOT NULL
 
);

ALTER TABLE TB_RESOURCE_FILE ADD CONSTRAINT PK_TB_RESOURCE_FILE
	PRIMARY KEY (ID);

CREATE TABLE TB_RESOURCE_METADATA_FILE (
  ID BIGINT NOT NULL,
  FILE_NAME varchar(500),
  EXTENSION varchar(10),
  FILE_FK BIGINT NOT NULL,
  UPDATE_DATE_TZ VARCHAR(50),
  UPDATE_DATE TIMESTAMP,
  UUID VARCHAR(36) NOT NULL,
  CREATED_DATE_TZ VARCHAR(50),
  CREATED_DATE TIMESTAMP,
  CREATED_BY VARCHAR(50),
  LAST_UPDATED_TZ VARCHAR(50),
  LAST_UPDATED TIMESTAMP,
  LAST_UPDATED_BY VARCHAR(50),
  VERSION BIGINT NOT NULL
  
);


ALTER TABLE TB_RESOURCE_METADATA_FILE ADD CONSTRAINT PK_TB_RESOURCE_METADATA_FILE
	PRIMARY KEY (ID)
;

ALTER TABLE TB_RESOURCE_METADATA_FILE ADD CONSTRAINT FK_TB_RESOURCE_METADATA_FILE_FILE_FK
	FOREIGN KEY (FILE_FK) REFERENCES TB_RESOURCE_FILE (ID) ON DELETE CASCADE
;

ALTER TABLE TB_CAT_RESOURCE_ELEMENTS ADD COLUMN LOGO_FK  BIGINT;
ALTER TABLE TB_CAT_RESOURCE_ELEMENTS ADD CONSTRAINT FK_TB_CAT_RESOURCE_ELEMENTS_LOGO_FK FOREIGN KEY (LOGO_FK) REFERENCES TB_RESOURCE_METADATA_FILE (id);
ALTER TABLE TB_CAT_RESOURCE_ELEMENTS ADD COLUMN IS_VISIBLE  BOOLEAN DEFAULT TRUE;

commit;