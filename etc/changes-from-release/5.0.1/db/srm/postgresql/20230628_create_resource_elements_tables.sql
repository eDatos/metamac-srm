-- y tabla tb_cat_resource_elements que referencia a tb_resource_elements y que se usará para los elementos de tema.
-- -------------------------------------------------------------------------------------------------- 
 

-- TB_RESOURCE_ELEMENTS

CREATE TABLE TB_RESOURCE_ELEMENTS (
  ID BIGINT NOT NULL,
  VALID_FROM_TZ VARCHAR(50),
  VALID_FROM TIMESTAMP,
  VALID_TO_TZ VARCHAR(50),
  VALID_TO TIMESTAMP,
  UPDATE_DATE_TZ VARCHAR(50),
  UPDATE_DATE TIMESTAMP,
  UUID VARCHAR(36) NOT NULL,
  CREATED_DATE_TZ VARCHAR(50),
  CREATED_DATE TIMESTAMP,
  CREATED_BY VARCHAR(50),
  LAST_UPDATED_TZ VARCHAR(50),
  LAST_UPDATED TIMESTAMP,
  LAST_UPDATED_BY VARCHAR(50),
  VERSION BIGINT NOT NULL,
  IDENTIFIABLE_ARTEFACT_FK BIGINT NOT NULL,
  SHORT_NAME_FK BIGINT NOT NULL,
  COMMENT_FK BIGINT
);

ALTER TABLE TB_RESOURCE_ELEMENTS ADD CONSTRAINT PK_TB_RESOURCE_ELEMENTS
	PRIMARY KEY (ID);
	
ALTER TABLE TB_RESOURCE_ELEMENTS
    ADD CONSTRAINT UQ_TB_RESOURCE_ELEMENTS UNIQUE (UUID);	

ALTER TABLE TB_RESOURCE_ELEMENTS ADD CONSTRAINT FK_TB_RESOURCE_ELEMENTS_IDENTIFIABLE_ARTEFACT_FK
	FOREIGN KEY (IDENTIFIABLE_ARTEFACT_FK) REFERENCES TB_ANNOTABLE_ARTEFACTS (ID);
	
ALTER TABLE TB_RESOURCE_ELEMENTS ADD CONSTRAINT FK_TB_RESOURCE_ELEMENTS_SHORT_NAME_FK
	FOREIGN KEY (SHORT_NAME_FK) REFERENCES TB_INTERNATIONAL_STRINGS (ID);
	
ALTER TABLE TB_RESOURCE_ELEMENTS ADD CONSTRAINT FK_TB_RESOURCE_ELEMENTS_COMMENT_FK
	FOREIGN KEY (COMMENT_FK) REFERENCES TB_INTERNATIONAL_STRINGS (ID);

Insert into TB_SEQUENCES(SEQUENCE_NAME, SEQUENCE_NEXT_VALUE) VALUES ('M_RESOURCE_ELEMENTS', 1);

------- TB_CAT_RESOURCE_ELEMENTS
CREATE TABLE TB_CAT_RESOURCE_ELEMENTS (
	TB_RESOURCE_ELEMENTS BIGINT NOT NULL
);
ALTER TABLE TB_CAT_RESOURCE_ELEMENTS ADD CONSTRAINT FK_TB_CAT_RESOURCE_ELEMENTS_TB_RESOURCE_ELEMENTS
	FOREIGN KEY (TB_RESOURCE_ELEMENTS) REFERENCES TB_RESOURCE_ELEMENTS (ID);


ALTER TABLE TB_CAT_RESOURCE_ELEMENTS ADD CONSTRAINT PK_TB_CAT_RESOURCE_ELEMENTS PRIMARY KEY (TB_RESOURCE_ELEMENTS);

commit;
